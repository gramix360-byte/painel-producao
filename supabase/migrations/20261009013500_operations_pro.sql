create or replace function private.log_order_timeline()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_title text;
  v_type text;
begin
  if tg_op='INSERT' then
    v_type:='created'; v_title:='Pedido recebido';
  elsif new.phase is distinct from old.phase then
    v_type:='phase';
    v_title:=case new.phase
      when 'arte_em_criacao' then 'Criação da arte iniciada'
      when 'aguardando_aprovacao' then 'Prévia enviada para aprovação'
      when 'arte_aprovada' then 'Arte aprovada pelo cliente'
      when 'em_producao' then 'Produção iniciada'
      when 'embalado' then 'Pedido embalado e conferido'
      when 'expedicao' then 'Pedido enviado'
      when 'entregue' then 'Pedido entregue'
      else 'Fase atualizada' end;
  elsif new.quality_status is distinct from old.quality_status then
    v_type:='quality'; v_title:='Qualidade: '||replace(new.quality_status,'_',' ');
  elsif new.payment_status is distinct from old.payment_status then
    v_type:='payment'; v_title:='Pagamento: '||replace(new.payment_status,'_',' ');
  else
    return new;
  end if;

  insert into public.order_timeline(order_id,event_type,title,details,created_by)
  values(new.id,v_type,v_title,jsonb_build_object(
    'phase',new.phase,'status',new.status,'quality_status',new.quality_status,
    'shipping_status',new.shipping_status,'payment_status',new.payment_status
  ),auth.uid());
  return new;
end
$$;

drop trigger if exists trg_order_timeline on public.orders;
create trigger trg_order_timeline
after insert or update of phase,quality_status,payment_status on public.orders
for each row execute function private.log_order_timeline();

insert into public.order_timeline(order_id,event_type,title,details)
select o.id,'created','Pedido recebido',jsonb_build_object('phase',o.phase,'status',o.status)
from public.orders o
where not exists(select 1 from public.order_timeline t where t.order_id=o.id);

create or replace function public.koda_create_snapshot()
returns uuid
language plpgsql
security definer
set search_path = 'public'
as $$
declare v_id uuid; v_snapshot jsonb;
begin
  if not public.koda_has_role(array['admin']) then raise exception 'Acesso negado'; end if;
  v_snapshot := jsonb_build_object(
    'created_at', now(),
    'customers', coalesce((select jsonb_agg(to_jsonb(t)) from public.customers t), '[]'::jsonb),
    'products', coalesce((select jsonb_agg(to_jsonb(t)) from public.products t), '[]'::jsonb),
    'materials', coalesce((select jsonb_agg(to_jsonb(t)) from public.materials t), '[]'::jsonb),
    'product_materials', coalesce((select jsonb_agg(to_jsonb(t)) from public.product_materials t), '[]'::jsonb),
    'material_consumptions', coalesce((select jsonb_agg(to_jsonb(t)) from public.material_consumptions t), '[]'::jsonb),
    'orders', coalesce((select jsonb_agg(to_jsonb(t)) from public.orders t), '[]'::jsonb),
    'order_items', coalesce((select jsonb_agg(to_jsonb(t)) from public.order_items t), '[]'::jsonb),
    'order_quality_checks', coalesce((select jsonb_agg(to_jsonb(t)) from public.order_quality_checks t), '[]'::jsonb),
    'order_timeline', coalesce((select jsonb_agg(to_jsonb(t)) from public.order_timeline t), '[]'::jsonb),
    'quotes', coalesce((select jsonb_agg(to_jsonb(t)) from public.quotes t), '[]'::jsonb),
    'quote_items', coalesce((select jsonb_agg(to_jsonb(t)) from public.quote_items t), '[]'::jsonb),
    'suppliers', coalesce((select jsonb_agg(to_jsonb(t)) from public.suppliers t), '[]'::jsonb),
    'purchases', coalesce((select jsonb_agg(to_jsonb(t)) from public.purchases t), '[]'::jsonb),
    'cash_transactions', coalesce((select jsonb_agg(to_jsonb(t)) from public.cash_transactions t), '[]'::jsonb),
    'marketing_posts', coalesce((select jsonb_agg(to_jsonb(t)) from public.marketing_posts t), '[]'::jsonb),
    'bank_accounts', coalesce((select jsonb_agg(to_jsonb(t)) from public.bank_accounts t), '[]'::jsonb),
    'company_settings', coalesce((select jsonb_agg(to_jsonb(t)) from public.company_settings t), '[]'::jsonb)
  );
  insert into public.koda_backup_snapshots(created_by,snapshot) values(auth.uid(),v_snapshot) returning id into v_id;
  delete from public.koda_backup_snapshots where created_at < now() - interval '30 days';
  return v_id;
end
$$;
