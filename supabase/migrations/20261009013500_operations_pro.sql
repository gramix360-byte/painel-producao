create or replace function public.koda_set_quality_check(
  p_order_id uuid,
  p_check_key text,
  p_completed boolean,
  p_note text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_total integer;
  v_completed integer;
begin
  if not public.koda_has_role(array['admin','producao']) then
    raise exception 'Acesso negado';
  end if;

  update public.order_quality_checks
  set completed = p_completed,
      note = nullif(trim(coalesce(p_note,'')),''),
      completed_at = case when p_completed then now() else null end,
      completed_by = case when p_completed then auth.uid() else null end,
      updated_at = now()
  where order_id = p_order_id and check_key = p_check_key;

  if not found then raise exception 'Verificação não encontrada'; end if;

  select count(*),count(*) filter(where completed)
  into v_total,v_completed
  from public.order_quality_checks where order_id=p_order_id;

  update public.orders
  set quality_status = case
        when v_total > 0 and v_completed = v_total then 'aprovado'
        when v_completed > 0 then 'em_conferencia'
        else 'pendente' end,
      quality_completed_at = case when v_total > 0 and v_completed = v_total then now() else null end,
      quality_completed_by = case when v_total > 0 and v_completed = v_total then auth.uid() else null end,
      updated_at = now()
  where id = p_order_id;

  return jsonb_build_object('total',v_total,'completed',v_completed,'approved',v_total>0 and v_total=v_completed);
end
$$;

create or replace function public.koda_pack_order(p_order_id uuid)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if not public.koda_has_role(array['admin','producao']) then
    raise exception 'Acesso negado';
  end if;
  if exists(select 1 from public.order_quality_checks where order_id=p_order_id and not completed)
     or not exists(select 1 from public.order_quality_checks where order_id=p_order_id) then
    raise exception 'Conclua todas as verificações de qualidade antes de embalar';
  end if;
  update public.orders
  set phase='embalado',status='finalizado',finished_at=coalesce(finished_at,now()),updated_at=now()
  where id=p_order_id and deleted_at is null;
  if not found then raise exception 'Pedido não encontrado'; end if;
end
$$;

