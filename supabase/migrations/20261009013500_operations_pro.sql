create or replace function private.refresh_order_estimate(p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare v_days integer;
begin
  select greatest(1,ceil(coalesce(sum(
    oi.quantity::numeric / greatest(coalesce(p.production_capacity_per_day,50),1)
  ),1)))::integer
  into v_days
  from public.order_items oi
  left join public.products p on p.id=oi.product_id
  where oi.order_id=p_order_id;

  update public.orders
  set estimated_completion_date = current_date + v_days,
      updated_at = now()
  where id=p_order_id and phase not in ('embalado','expedicao','entregue');
end
$$;

create or replace function private.order_item_refresh_estimate()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.refresh_order_estimate(coalesce(new.order_id,old.order_id));
  return coalesce(new,old);
